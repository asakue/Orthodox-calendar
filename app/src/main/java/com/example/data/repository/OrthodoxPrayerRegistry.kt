    fun getPrayersForHoliday(holiday: OrthodoxHoliday): List<PrayerItem> {
        val matchedList = mutableListOf<PrayerItem>()

        // Specific holiday troparion & prayer
        matchedList.add(
            PrayerItem(
                id = "troparion_${holiday.id}",
                title = "Тропарь и Кондак праздника (${holiday.title})",
                category = "Богослужебные тексты",
                targetFeastOrSaint = holiday.title,
                text = "ТРОПАРЬ (${holiday.troparionTone}):\n${holiday.troparion}\n\nКОНДАК (${holiday.kontakionTone}):\n${holiday.kontakion}" +
                        if (holiday.magnification.isNotEmpty()) "\n\nВЕЛИЧАНИЕ:\n${holiday.magnification}" else "",
                translation = "Священные песнопения, раскрывающие сущность праздника.",
                commentary = "Читаются или поются во время Божественной Литургии и домашней молитвы."
            )
        )

        matchedList.add(
            PrayerItem(
                id = "prayer_feast_${holiday.id}",
                title = "Молитва в день ${holiday.title}",
                category = "Молитвы праздника",
                targetFeastOrSaint = holiday.title,
                text = holiday.prayer,
                translation = "Особая церковная молитва дня.",
                commentary = "Читается с благоговением о ниспослании благодати праздника."
            )
        )

        return matchedList
    }
